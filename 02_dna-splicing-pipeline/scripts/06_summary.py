#!/usr/bin/env python3
"""
Phase 1, step 6: write results/phase1_summary.md from the numbers the earlier steps saved.

    python scripts/06_summary.py

Reads data/label_info.json, results/phase1_results.json, results/embed_stats.json
and (when run through run_all.sh) results/run_steps.tsv for wall-clock times.
Nothing in the summary is typed by hand, so rerunning the pipeline keeps it
in sync with the results.
"""

import math
import sys
from datetime import datetime, timezone

from phase1_common import (EMBED_STATS_JSON, LABEL_INFO_PATH, MODELS, RESULTS_DIR,
                           RESULTS_JSON, RUN_STEPS_TSV, read_json)

OUT_MD = RESULTS_DIR / "phase1_summary.md"
FLAG_ACCURACY = 0.97
VARIANT_ORDER = ["full_mean", "center_tok", "center_w10", "center_w25", "center_w50",
                 "concat_c25_full", "prev_tok", "center_plus_prev", "center_plus_prev_concat"]
VARIANT_BASES = {"full_mean": "all 0–599", "center_tok": "token covering 300",
                 "center_w10": "290–310", "center_w25": "275–325", "center_w50": "250–350",
                 "concat_c25_full": "275–325 ++ all", "prev_tok": "token before the centre",
                 "center_plus_prev": "centre + previous (mean)",
                 "center_plus_prev_concat": "centre ++ previous"}


def ci95(acc, n):
    """Half-width of a normal-approximation 95% interval for an accuracy."""
    return 1.96 * math.sqrt(max(acc * (1 - acc), 1e-12) / n)


def fmt_dur(seconds):
    seconds = int(round(seconds))
    h, rem = divmod(seconds, 3600)
    m, s = divmod(rem, 60)
    return f"{h}h {m:02d}m {s:02d}s" if h else f"{m}m {s:02d}s"


def read_steps():
    if not RUN_STEPS_TSV.exists():
        return None, []
    start, steps = None, []
    for line in RUN_STEPS_TSV.read_text().splitlines():
        parts = line.split("\t")
        if line.startswith("# started_epoch"):
            start = float(parts[1])
        elif len(parts) == 3:
            steps.append((parts[0], parts[1], int(parts[2])))
    return start, steps


def main():
    info = read_json(LABEL_INFO_PATH)
    res = read_json(RESULTS_JSON) or {}
    stats = read_json(EMBED_STATS_JSON) or {}
    if not info or not res:
        print("Missing label_info.json or phase1_results.json; run steps 01-04 first.",
              file=sys.stderr)
        return 1

    base = res.get("baseline", {})
    models = res.get("models", {})
    names = info["names"]
    order = [names[str(c)] for c in info["label_values"]]

    rows = []   # (method, n, metrics, kind)
    ra = base.get("single_offset_rule")
    rb = base.get("strand_aware_rule")
    if ra:
        rows.append((f"GT/AG rule, one offset ({ra['best_offset']}), as specified",
                     ra["model_subset"]["n"], ra["model_subset"], "baseline"))
    if rb and "model_subset" in rb:
        o = rb["offsets_selected_on_train"]
        rows.append((f"GT/AG rule, strand-aware (GT@{o['GT']}/AC@{o['AC']}, "
                     f"AG@{o['AG']}/CT@{o['CT']})", rb["model_subset"]["n"],
                     rb["model_subset"], "baseline"))
    for repo, short in MODELS.items():
        m = models.get(repo)
        if not m:
            rows.append((f"{short} + MLP head", None, None, "model"))
            continue
        rows.append((f"{short} + MLP head", m["n_test"], m["mlp"], "model"))
        rows.append((f"{short} + logistic regression", m["n_test"], m["logreg"], "reference"))

    md = ["# Phase 1 summary: splice-site classification with frozen DNA language models\n",
          f"_Generated by `scripts/06_summary.py` on "
          f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} from "
          "`results/phase1_results.json` and `results/embed_stats.json`._\n"]

    # ---------- dataset ----------
    sm = info.get("strand_mix", {})
    md.append("## The dataset\n")
    md.append(f"`{info['dataset_repo']}`, task `{info['dataset_config']}`: human splice sites "
              "from GENCODE V44 (the Nucleotide Transformer revised downstream benchmark). "
              f"Every row is a {info['sequence_length']}-nt DNA window with one label for the "
              "whole window: is the centre of the window a **donor** site (exon→intron), an "
              "**acceptor** site (intron→exon), or **neither**. 30,000 train and 3,000 test "
              "windows, roughly balanced, with the test set on held-out chromosomes. It is "
              "window classification. It is not locating a cut point inside a long sequence. "
              "Details: `results/dataset_format.md`.\n")
    md.append(f"- Label values: " + ", ".join(f"`{k}` = {v}" for k, v in names.items()) +
              f". **{info['status'].capitalize()}** from motif enrichment, because the dataset "
              "card does not document them.")
    if sm:
        md.append(f"- Windows are on the genome + strand. About half the sites appear "
                  f"reverse-complemented: donors show GT at offset "
                  f"{info['motif_offsets_0based']['donor_GT_plus']} in {sm['donor_plus']:.0%} of "
                  f"rows and AC at offset {info['motif_offsets_0based']['donor_AC_minus']} in "
                  f"{sm['donor_minus']:.0%}. Acceptors show the same split with AG and CT.")
    md.append("")

    # ---------- sequences used ----------
    md.append("## How many sequences were used\n")
    md.append("| method | train rows | test rows |")
    md.append("|---|---:|---:|")
    for repo, short in MODELS.items():
        m = models.get(repo)
        if m:
            md.append(f"| {short} embeddings + heads | {m['n_train']:,} of 30,000 "
                      f"(class-stratified, seed 42) | {m['n_test']:,} of 3,000 |")
        else:
            md.append(f"| {short} embeddings + heads | not run / failed | n/a |")
    if ra:
        md.append(f"| GT/AG baselines | none (the strand-aware offsets are picked on all "
                  f"30,000 train rows) | {ra['model_subset']['n']:,} (same rows as the models); "
                  f"{ra['full_test']['n']:,} full test in the JSON |")
    md.append("\nThe MLP head is fit on 90% of its train rows. The other 10% is its "
              "early-stopping validation split. Logistic regression is fit on all train rows.\n")

    # ---------- results table ----------
    md.append("## Results on the test windows\n")
    md.append("| method | test n | accuracy (±95% CI) | macro-F1 | "
              + " | ".join(f"F1 {c}" for c in order) + " |")
    md.append("|---|---:|---:|---:|" + "---:|" * len(order))
    for method, n, m, kind in rows:
        if m is None:
            md.append(f"| {method} | n/a | **not run / failed** | n/a |" + " n/a |" * len(order))
            continue
        bold = "**" if kind == "model" else ""
        pc = " | ".join(f"{m['per_class'][c]['f1']:.3f}" for c in order)
        md.append(f"| {bold}{method}{bold} | {n:,} | {bold}{m['accuracy']:.3f}{bold} "
                  f"(±{ci95(m['accuracy'], n):.3f}) | {m['macro_f1']:.3f} | {pc} |")
    md.append("\nChance is 0.333 (three balanced classes). Chart: "
              "`results/phase1_comparison.png`. Confusion matrices and per-class "
              "precision and recall are in `results/phase1_results.json`.\n")

    # ---------- who won ----------
    md.append("## Which model won\n")
    mlps = [(MODELS[r], models[r]["mlp"], models[r]["n_test"]) for r in MODELS if r in models]
    if len(mlps) == 2:
        (n1, m1, t1), (n2, m2, t2) = sorted(mlps, key=lambda t: -t[1]["accuracy"])
        gap = m1["accuracy"] - m2["accuracy"]
        gap_f1 = m1["macro_f1"] - m2["macro_f1"]
        noise = math.sqrt(ci95(m1["accuracy"], t1) ** 2 + ci95(m2["accuracy"], t2) ** 2)
        verdict = ("larger than the ~±{:.1f} pp sampling noise of the difference".format(noise * 100)
                   if abs(gap) > noise else
                   "within the ~±{:.1f} pp sampling noise of the difference, so this is "
                   "not a clear win".format(noise * 100))
        md.append(f"**{n1} + MLP head** beat {n2} + MLP head by **{gap * 100:.1f} percentage "
                  f"points of accuracy** ({m1['accuracy']:.3f} vs {m2['accuracy']:.3f}) and "
                  f"{gap_f1 * 100:.1f} points of macro-F1 ({m1['macro_f1']:.3f} vs "
                  f"{m2['macro_f1']:.3f}). The accuracy gap is {verdict}.\n")
    elif len(mlps) == 1:
        md.append(f"Only {mlps[0][0]} produced results, so there is no head-to-head comparison.\n")
    else:
        md.append("No model produced results.\n")

    vsel = res.get("variant_selection", {}).get("models", {})
    picks = {MODELS[r]: v for r, v in vsel.items() if r in MODELS and v.get("final_test")}
    if len(picks) == 2:
        (n1, p1), (n2, p2) = sorted(picks.items(), key=lambda kv: -kv[1]["final_test"]["accuracy"])
        f1, f2 = p1["final_test"], p2["final_test"]
        gap = f1["accuracy"] - f2["accuracy"]
        noise = math.sqrt(ci95(f1["accuracy"], f1["n"]) ** 2 + ci95(f2["accuracy"], f2["n"]) ** 2)
        md.append(f"**With position-aware pooling the answer changes.** With each model's "
                  f"pooling variant chosen on a validation split (never on test; see "
                  f"*Choosing the pooling variant without the test set*), **{n1} "
                  f"`{p1['selected_variant']}`** ({f1['accuracy']:.3f} accuracy, "
                  f"{f1['macro_f1']:.3f} macro-F1) beats {n2} `{p2['selected_variant']}` "
                  f"({f2['accuracy']:.3f}, {f2['macro_f1']:.3f}) by **{gap * 100:.1f} points**. "
                  f"That gap is {'larger than' if gap > noise else 'within'} the "
                  f"~±{noise * 100:.1f} pp sampling noise. The full-window comparison above "
                  "mostly measured how much each model's average washes out the centre.\n")

    if ra:
        md.append("## The no-ML baseline\n")
        md.append(f"- **As specified** (one offset, GT→donor, AG→acceptor, best offset "
                  f"{ra['best_offset']} chosen on test): accuracy "
                  f"**{ra['model_subset']['accuracy']:.3f}**, macro-F1 "
                  f"{ra['model_subset']['macro_f1']:.3f} on the model test rows "
                  f"({ra['full_test']['accuracy']:.3f} / {ra['full_test']['macro_f1']:.3f} on "
                  f"all 3,000). Picking the offset on train instead gives offset "
                  f"{ra['offset_selected_on_train']} and {ra['full_test_at_train_offset']['accuracy']:.3f}. "
                  "This rule is capped near 0.5: one offset sees only the + strand motif of one "
                  "site type, because donor GT and acceptor AG sit at different offsets and "
                  "half the windows are reverse-complemented.")
        if rb and "model_subset" in rb:
            md.append(f"- **Strand-aware** (same motifs, reverse complements included, offsets "
                      f"picked on train only): accuracy **{rb['model_subset']['accuracy']:.3f}**, "
                      f"macro-F1 {rb['model_subset']['macro_f1']:.3f} "
                      f"({rb['full_test']['accuracy']:.3f} / {rb['full_test']['macro_f1']:.3f} "
                      "on all 3,000). This is the fair no-learning reference point.")
            if mlps:
                best_name, best_m, _ = max(mlps, key=lambda t: t[1]["accuracy"])
                d = best_m["accuracy"] - rb["model_subset"]["accuracy"]
                md.append(f"- Best frozen model with full-window mean pooling vs the strand-aware "
                          f"rule: {best_name} + MLP is "
                          f"**{abs(d) * 100:.1f} points {'above' if d > 0 else 'below'}** it.")
        md.append("")

    # ---------- pooling variants ----------
    pv = res.get("pooling_variants", {})
    cstats = stats.get("center_pooling", {})
    if pv:
        ref = rb["model_subset"] if rb and "model_subset" in rb else None
        md.append("## Pooling variants: pooling near the centre instead of the whole window\n")
        md.append("`scripts/02b_embed_center.py` maps every token back to the bases it covers "
                  "(DNABERT-2: the fast tokenizer's offsets; NT-v2: cumulative token lengths, "
                  "checked to spell the sequence exactly) and pools only near the splice "
                  "junction (about base 300). All variants come from the same frozen forward pass, "
                  "rows and head as above. Base ranges are inclusive. A token counts if it "
                  "overlaps the range.\n")
        head = "| variant | bases pooled | model | tokens pooled | MLP accuracy | MLP macro-F1 | " \
               "LogReg accuracy | LogReg macro-F1 | MLP vs strand-aware rule |"
        md.append(head)
        md.append("|---|---|---|---:|---:|---:|---:|---:|---|")
        beat, not_beat, flagged, all_acc = [], [], [], []
        for v in VARIANT_ORDER:
            for repo, short in MODELS.items():
                e = models.get(repo) if v == "full_mean" else pv.get(repo, {}).get(v)
                if not e:
                    md.append(f"| `{v}` | {VARIANT_BASES[v]} | {short} | n/a | **not run** | "
                              "n/a | n/a | n/a | n/a |")
                    continue
                tp = cstats.get(repo, {}).get("tokens_pooled_per_sequence", {})
                if v == "concat_c25_full":
                    ntok = (f"{tp['center_w25']['mean']:.1f} + {tp['full_mean']['mean']:.0f}"
                            if tp else "n/a")
                else:
                    ntok = f"{tp[v]['mean']:.1f}" if v in tp else "n/a"
                m, lr = e["mlp"], e["logreg"]
                all_acc.append((m["accuracy"], f"{short} `{v}` MLP"))
                all_acc.append((lr["accuracy"], f"{short} `{v}` LogReg"))
                for h, mm in (("MLP", m), ("LogReg", lr)):
                    if mm["accuracy"] > FLAG_ACCURACY:
                        flagged.append(f"{short} `{v}` {h}: {mm['accuracy']:.3f}")
                if ref:
                    d = m["accuracy"] - ref["accuracy"]
                    verdict = f"{'**beats**' if d > 0 else 'below'} ({d * 100:+.1f} pts)"
                    (beat if d > 0 else not_beat).append(
                        f"{short} `{v}` ({m['accuracy']:.3f}, {d * 100:+.1f} pts)")
                else:
                    verdict = "n/a"
                md.append(f"| `{v}` | {VARIANT_BASES[v]} | {short} | {ntok} | "
                          f"**{m['accuracy']:.3f}** | {m['macro_f1']:.3f} | {lr['accuracy']:.3f} | "
                          f"{lr['macro_f1']:.3f} | {verdict} |")
        if ref:
            md.append(f"\nReference: strand-aware GT/AG rule, no learning, on the same "
                      f"{ref['n']:,} test rows: accuracy **{ref['accuracy']:.3f}**, macro-F1 "
                      f"{ref['macro_f1']:.3f}. Chart: `results/phase1_pooling_variants.png` "
                      "(dashed line = this rule).\n")
            noise = math.sqrt(2) * ci95(ref["accuracy"], ref["n"])
            md.append(f"**Beat the {ref['accuracy']:.3f} rule (MLP head accuracy):** "
                      + ("; ".join(beat) if beat else "none") + ".\n")
            md.append(f"**Did not beat it:** " + ("; ".join(not_beat) if not_beat else "none")
                      + ".\n")
            md.append(f"Differences within about ±{noise * 100:.1f} points of the rule are inside "
                      f"test-set sampling noise at n = {ref['n']:,}. The rows are shared, so a "
                      "paired test would be somewhat tighter. This table compares variants on "
                      "test for description only. The variant each model is *reported* with is "
                      "chosen on a validation split in the next section.\n")
        if flagged:
            md.append("> **⚠ FLAG: accuracy above 0.97.** " + "; ".join(flagged) + ". The "
                      "motif alone gets ~0.89, so a near-perfect score suggests the head is "
                      "reading the centre motif almost literally (e.g. from the identity of the "
                      "token that contains it) rather than using sequence context. Check this "
                      "before relying on the number.\n")
        elif all_acc:
            top = max(all_acc)
            md.append(f"No variant scored above {FLAG_ACCURACY} accuracy (highest: "
                      f"{top[1]} at {top[0]:.3f}).\n")
        anyc = next(iter(cstats.values()), None)
        if anyc:
            md.append("Raw last-layer vectors for every token overlapping bases 240–360 are "
                      "saved as float16 in `data/emb/<model>/center_tokens.npy`. The per-sequence "
                      "index and each token's base span are in `center_tokens_index.npz`. Any "
                      "other pooling width inside 240–360 can be built from these without "
                      "another forward pass.\n")

    # ---------- validation-only variant selection ----------
    vs = res.get("variant_selection")
    if vs and vs.get("models"):
        md.append("## Choosing the pooling variant without the test set\n")
        any_m = next(iter(vs["models"].values()))
        md.append(f"Protocol: a selection split of {any_m['n_selection']:,} training rows "
                  f"({vs['sel_frac']:.0%}, class-stratified, seed {vs['seed']}) is held out. For "
                  f"each variant, the same MLP recipe is trained on the other "
                  f"{any_m['n_selection_fit']:,} rows. It carves its own early-stopping split from "
                  "those, so it does not reuse 03's early-stopping split (the two overlap by "
                  f"{any_m['overlap_with_03_early_stopping_rows']} rows, about the "
                  f"{any_m['n_selection'] // 10} expected by chance). The variant with the best "
                  "selection-split accuracy is chosen. Its final number is the test score of the "
                  "03 head refit on all training rows. The test set plays no part in the choice.\n")
        md.append("| variant | " + " | ".join(f"{m['short_name']} selection-split acc"
                                              for m in vs["models"].values()) + " |")
        md.append("|---|" + "---:|" * len(vs["models"]))
        for v in VARIANT_ORDER:
            cells = []
            for m in vs["models"].values():
                sv = m["selection_split"].get(v)
                mark = " ◀ chosen" if v == m["selected_variant"] else ""
                cells.append(f"{sv['accuracy']:.3f}{mark}" if sv else "n/a")
            md.append(f"| `{v}` | " + " | ".join(cells) + " |")
        md.append("")
        md.append("| model | chosen on validation | validation acc / macro-F1 | **final test "
                  "acc / macro-F1** | test-picked (leaky) best | change vs leaky |")
        md.append("|---|---|---:|---:|---:|---:|")
        for m in vs["models"].values():
            ft, lk = m["final_test"], m["leaky_test_selected"]
            md.append(f"| {m['short_name']} | `{m['selected_variant']}` | "
                      f"{m['selected_val_accuracy']:.3f} / {m['selected_val_macro_f1']:.3f} | "
                      f"**{ft['accuracy']:.3f} / {ft['macro_f1']:.3f}** | "
                      f"{lk['accuracy']:.3f} (`{lk['variant']}`) | "
                      f"{m['moved_vs_leaky_points']:+.1f} pts |")
        md.append("")
        for m in vs["models"].values():
            lk = m["leaky_test_selected"]
            if lk["variant"] == m["selected_variant"]:
                md.append(f"- **{m['short_name']}:** validation picks the same variant as the "
                          f"test table did (`{m['selected_variant']}`), so the reported number "
                          f"did not move ({m['final_test']['accuracy']:.3f}). The leak "
                          "inflated nothing here, but the number is now obtained honestly.")
            else:
                md.append(f"- **{m['short_name']}:** validation picks `{m['selected_variant']}` "
                          f"instead of the test-picked `{lk['variant']}`. The reported number "
                          f"moves from {lk['accuracy']:.3f} to {m['final_test']['accuracy']:.3f} "
                          f"({m['moved_vs_leaky_points']:+.1f} points).")
        md.append("")

    # ---------- motif analysis (09) ----------
    ma = RESULTS_DIR / "motif_analysis.md"
    if ma.exists():
        body = ma.read_text().splitlines()
        body = [ln for ln in body if not ln.startswith("# ") and not ln.startswith("_Generated")]
        body = [("#" + ln) if ln.startswith("## ") else ln for ln in body]
        while body and not body[0].strip():
            body.pop(0)
        body = [ln for i, ln in enumerate(body) if ln.strip() or (i and body[i - 1].strip())]
        md.append("## What the language model does that the motif rule cannot\n")
        md.append("_From `scripts/09_motif_analysis.py`; full output in "
                  "`results/motif_analysis.md` and `.json`._\n")
        md.extend(body)
        md.append("")

    # ---------- position scan (10/11) ----------
    ps = read_json(RESULTS_DIR / "position_scan.json")
    if ps and ps.get("pooled") and ps.get("order"):
        md.append("## From windows to whole genes\n")
        pos = ps["positives"]
        n_minus = sum(g["strand"] == "-" for g in ps["genes"].values())
        md.append("The validation-chosen per-position heads were applied at every position of "
                  f"{len(ps['genes'])} genes from the held-out test chromosomes chr20/chr21 "
                  f"({n_minus} on the − strand; {pos['donors']} donors and {pos['acceptors']} "
                  f"acceptors), where positives are about 1 in {pos['one_site_per_bases']:,} "
                  "positions. Pooled top-k accuracy (within 2 bases) and AUROC over every "
                  "position, with 95% intervals from resampling genes:\n")
        md.append("| track | top-k donors | top-k acceptors | AUROC donors | AUROC acceptors |")
        md.append("|---|---:|---:|---:|---:|")
        for m in ps["order"]:
            v = ps["pooled"][m]

            def f(x, d=2):
                return f"{x['value']:.{d}f} [{x['ci95'][0]:.{d}f}, {x['ci95'][1]:.{d}f}]"
            md.append(f"| {m} | {f(v['donor']['top_k'])} | {f(v['acceptor']['top_k'])} | "
                      f"{f(v['donor']['auroc'], 3)} | {f(v['acceptor']['auroc'], 3)} |")
        hh = res.get("hardneg_heads", {})
        vh = res.get("variant_selection_hardneg", {}).get("models", {})
        rows = []
        for repo, short in MODELS.items():
            v = vh.get(repo, {}).get("selected_variant")
            e = hh.get(repo, {}).get(v, {}).get("mlp") if v else None
            if e:
                rows.append(f"{short} `{v}` {e['accuracy']:.4f}")
        if rows:
            md.append("\nHard-negative heads (13: exon interiors, intron interiors and GT/AG "
                      "decoys from training-chromosome genes, same recipe, same 07 protocol), "
                      "test accuracy on the original test windows: " + "; ".join(rows) + ".")
        md.append("\nFull report, the paired track comparisons, false positives at matched "
                  "recall (current vs hard-negative head, exon vs intron) and the composition "
                  "control: `results/position_scan_summary.md`.\n")

    # ---------- tokens and time ----------
    md.append("## Tokens and compute\n")
    md.append("| model | tokens / sequence (mean, min–max) | ms / sequence (CPU) | "
              "embedding compute | sequences embedded |")
    md.append("|---|---:|---:|---:|---:|")
    for repo, short in MODELS.items():
        s = stats.get(repo)
        if not s:
            md.append(f"| {short} | n/a | n/a | n/a | not run |")
            continue
        t = s["tokens_per_sequence"]
        md.append(f"| {short} | {t['mean']:.1f} ({t['min']}–{t['max']}) | "
                  f"{s['seconds_per_sequence'] * 1000:.0f} | {fmt_dur(s['embed_compute_seconds'])} | "
                  f"{s['n_train'] + s['n_test']:,} |")
    def n_seq(repo):
        st = stats.get(repo, {})
        return st.get("n_train", 0) + st.get("n_test", 0)

    for repo, short in MODELS.items():
        c = stats.get("center_pooling", {}).get(repo)
        if c:
            md.append(f"| {short}, centre-pooling pass (02b) | same tokens | "
                      f"{c['seconds_per_sequence'] * 1000:.0f} | {fmt_dur(c['embed_compute_seconds'])} | "
                      f"{c.get('n_embedded', n_seq(repo)):,} |")
    trunc = {MODELS[r]: stats[r]["n_truncated"] for r in MODELS if r in stats}
    trunc_txt = ("No sequence was truncated." if not any(trunc.values()) else
                 "Truncated sequences: " + ", ".join(f"{k}: {v}" for k, v in trunc.items()) + ".")
    md.append("\nToken counts include the special tokens (CLS, and SEP for DNABERT-2) for a "
              "600-nt window. NT-v2 splits DNA into non-overlapping 6-mers. DNABERT-2 uses "
              f"learned BPE pieces of variable length. {trunc_txt}\n")

    start, steps = read_steps()
    if start:
        # Sum of recorded steps, so rerunning this script on its own later
        # does not inflate the number.
        total = sum(secs for _, _, secs in steps)
        md.append(f"**Total wall-clock for the run that produced these results: "
                  f"{fmt_dur(total)}** (`scripts/run_all.sh`, CPU only, started "
                  f"{datetime.fromtimestamp(start).strftime('%Y-%m-%d %H:%M')}).\n")
        md.append("| step | status | time |")
        md.append("|---|---|---:|")
        for name, rc, secs in steps:
            status = "ok" if rc == "0" else ("skipped" if rc == "skipped" else f"FAILED (exit {rc})")
            md.append(f"| {name} | {status} | {fmt_dur(secs)} |")
        md.append("\nIf an embedding step shows a few seconds, it reused embeddings already on "
                  "disk. The compute table above gives the original embedding time.\n")
    else:
        md.append("Wall-clock: not recorded (steps were run by hand, not through run_all.sh).\n")

    # ---------- limitations ----------
    md.append("## Limitations\n")
    md.append("- **The backbone is frozen, not fine-tuned.** Only a small head on top of a fixed "
              "vector is trained. The headline published results for these models on this "
              "benchmark come from fine-tuning (all weights, or parameter-efficient "
              "adapters), so these numbers should sit "
              "**below** published fine-tuned results. They are a lower bound on what these "
              "models can do, not a measure of it.")
    if pv:
        md.append("- **Pooling choice.** The reported variant is chosen on a validation split "
                  "carved from train, not on test. The full variant table is shown on test for "
                  "description only.")
        md.append("- **Small non-canonical group.** Only a handful of true splice sites lack the "
                  "canonical motif (see the motif analysis), so recall on them has a wide "
                  "interval. The decoy rows and the composition control carry most of the "
                  "evidence that the models use more than the motif.")
    else:
        md.append("- **Mean pooling throws away position.** The label depends on what sits "
                  "exactly at the centre of the window, but the whole window is averaged into "
                  "one vector. Pooling only the tokens around the centre, or keeping per-token "
                  "vectors, would likely help. It needs one more embedding pass at the same cost "
                  "as this run, and it is the obvious next step.")
    md.append("- **Subsampled data.** Each model saw a class-stratified subset of the 30,000 "
              "training windows (see the sequence counts above) to keep a CPU run under an hour. "
              "`--max-train -1 --max-test -1` uses everything.")
    md.append("- **One seed, untuned heads.** One train/validation split and default "
              "hyperparameters, with no repeated runs. The ±95% intervals cover test-set "
              "sampling only, not training variance.")
    md.append("- **Label names are inferred**, not documented. The motif evidence is "
              "overwhelming (see `dataset_format.md`) but it is still an inference.")
    md.append("- **Baseline selection.** The as-specified rule's offset was picked on the test "
              "set, as requested, which flatters it slightly. The strand-aware rule's offsets "
              "were picked on train only.")
    md.append("- **The task differs from the advisor's framing.** This benchmark classifies a "
              "pre-centred window. Finding *where* to cut inside a long sequence is a "
              "different, harder task. It is closer to sliding this classifier along the "
              "sequence or to per-token prediction (SpliceAI-style).\n")

    OUT_MD.write_text("\n".join(md) + "\n")
    print(f"Wrote {OUT_MD}")
    return 0


